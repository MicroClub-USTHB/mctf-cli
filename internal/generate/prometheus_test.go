package generate

import (
	"testing"

	"github.com/MicroClub-USTHB/mctf-cli/internal/challenge"
	"github.com/MicroClub-USTHB/mctf-cli/internal/config"
)

func staticChall(slug string) *challenge.Challenge {
	return &challenge.Challenge{
		Slug:      slug,
		Archetype: challenge.ArchetypeStatic,
	}
}

func instancedChall(slug string, port int) *challenge.Challenge {
	p := port
	return &challenge.Challenge{
		Slug:      slug,
		Archetype: challenge.ArchetypeInstanced,
		Manifest: challenge.Manifest{
			Deploy: &challenge.DeployBlock{
				InternalPort: &p,
			},
		},
	}
}

const wantSingleJob = `#Auto generated by MCTF
scrape_configs:
  - job_name: "cub3"
    static_configs:
      - targets:
          - "localhost:8000"
`

func TestPrometheusConfig(t *testing.T) {
	tests := []struct {
		name   string
		challs []*challenge.Challenge
		want   string
	}{
		{
			name:   "Empty",
			challs: nil,
			want:   "#Auto generated by MCTF\nscrape_configs:\n",
		},
		{
			name: "SkipsNonInstanced",
			challs: []*challenge.Challenge{
				staticChall("static"),
				instancedChall("cub3", 8000),
			},
			want: wantSingleJob,
		},
		{
			name: "SkipsNilDeploy",
			challs: []*challenge.Challenge{
				{Slug: "cub3", Archetype: challenge.ArchetypeInstanced}, // No Deploy block
			},
			want: "#Auto generated by MCTF\nscrape_configs:\n",
		},
		{
			name: "SkipsNilPort",
			challs: []*challenge.Challenge{
				{
					Slug:      "cub3",
					Archetype: challenge.ArchetypeInstanced,
					Manifest: challenge.Manifest{
						Deploy: &challenge.DeployBlock{
							InternalPort: nil, // Port is nil
						},
					},
				},
			},
			want: "#Auto generated by MCTF\nscrape_configs:\n",
		},
		{
			name: "Sorted",
			challs: []*challenge.Challenge{
				instancedChall("z", 8003),
				instancedChall("a", 8001),
				instancedChall("m", 8002),
			},
			want: `#Auto generated by MCTF
scrape_configs:
  - job_name: "a"
    static_configs:
      - targets:
          - "localhost:8001"
  - job_name: "m"
    static_configs:
      - targets:
          - "localhost:8002"
  - job_name: "z"
    static_configs:
      - targets:
          - "localhost:8003"
`,
		},
		{
			name: "YAMLFormat",
			challs: []*challenge.Challenge{
				instancedChall("cub3", 8000),
			},
			want: wantSingleJob,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := PrometheusConfig(tt.challs)
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}
			if string(got) != tt.want {
				t.Errorf("got:\n%s\nwant:\n%s", string(got), tt.want)
			}
		})
	}
}

func TestShouldEmitPrometheus(t *testing.T) {
	tests := []struct {
		name   string
		cfg    *config.Config
		challs []*challenge.Challenge
		want   bool
	}{
		{
			name:   "NoInstanced",
			cfg:    &config.Config{},
			challs: []*challenge.Challenge{staticChall("static")},
			want:   false,
		},
		{
			name:   "HasInstanced",
			cfg:    &config.Config{},
			challs: []*challenge.Challenge{instancedChall("instanced", 8000)},
			want:   true,
		},
		{
			name: "MonitoringConfig",
			cfg: &config.Config{
				Monitoring: map[string]any{"enabled": true},
			},
			challs: []*challenge.Challenge{staticChall("static")},
			want:   true,
		},
		{
			name:   "NilCfg",
			cfg:    nil,
			challs: []*challenge.Challenge{instancedChall("instanced", 8000)},
			want:   true,
		},
		{
			name:   "NilCfgNoInstanced",
			cfg:    nil,
			challs: []*challenge.Challenge{staticChall("static")},
			want:   false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := shouldEmitPrometheus(tt.cfg, tt.challs); got != tt.want {
				t.Errorf("shouldEmitPrometheus() = %v, want %v", got, tt.want)
			}
		})
	}
}
