package generate

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/MicroClub-USTHB/mctf-cli/internal/challenge"
	"github.com/MicroClub-USTHB/mctf-cli/internal/config"
)

// InstanceTOML renders the instancer config for an instanced challenge.
//
// Returns nil bytes for non-instanced archetypes — callers should not write
// an instance.toml in that case (and should remove a stale one if present).
//
// We hand-render the TOML rather than going through a marshaller so the
// output preserves the human-readable shape (grouped sections separated by
// blank lines) and is byte-deterministic.
func InstanceTOML(cfg *config.Config, c *challenge.Challenge) ([]byte, error) {
	if c.Archetype != challenge.ArchetypeInstanced {
		return nil, nil
	}
	m := c.Manifest
	dep := m.Deploy
	if dep == nil {
		return nil, fmt.Errorf("%s: instanced challenge missing deploy block", c.Slug)
	}

	id := strings.ToLower(challenge.SlugFromName(m.Challenge.Name))
	if id == "" {
		id = c.Slug
	}
	t := "http"
	if dep.TCP {
		t = "tcp"
	}
	internalPort := 0
	if dep.InternalPort != nil {
		internalPort = *dep.InternalPort
	}
	timeout := defaultInt(cfg, dep, "timeout")
	extend := defaultInt(cfg, dep, "extend_time")
	maxPerTeam := 1
	if dep.Instance != nil && dep.Instance.MaxPerTeam > 0 {
		maxPerTeam = dep.Instance.MaxPerTeam
	}

	var buf bytes.Buffer
	buf.WriteString("# Auto-generated by MCTF (do not edit this file directly)\n\n")
	fmt.Fprintf(&buf, "id = %q\n", id)
	fmt.Fprintf(&buf, "name = %q\n", m.Challenge.Name)
	fmt.Fprintf(&buf, "category = %q\n", m.Challenge.Category)
	fmt.Fprintf(&buf, "description = %q\n", strings.TrimSpace(m.Challenge.Description))
	buf.WriteString("\n")
	fmt.Fprintf(&buf, "type = %q\n", t)
	fmt.Fprintf(&buf, "ports = [%d]\n", internalPort)
	fmt.Fprintf(&buf, "timeout = %d\n", timeout)
	fmt.Fprintf(&buf, "extend_time = %d\n", extend)
	fmt.Fprintf(&buf, "max_per_team = %d\n", maxPerTeam)

	if dep.Resources != nil {
		buf.WriteString("\n[resources]\n")
		if dep.Resources.CPU != "" {
			fmt.Fprintf(&buf, "cpu = %q\n", dep.Resources.CPU)
		}
		if dep.Resources.Memory != "" {
			fmt.Fprintf(&buf, "memory = %q\n", dep.Resources.Memory)
		}
		if dep.Resources.PIDs > 0 {
			fmt.Fprintf(&buf, "pids = %d\n", dep.Resources.PIDs)
		}
	}
	return buf.Bytes(), nil
}

// defaultInt picks the timeout/extend_time using per-challenge override,
// then event default, then a hardcoded fallback (1800 / 900).
func defaultInt(cfg *config.Config, dep *challenge.DeployBlock, field string) int {
	if dep.Instance != nil {
		switch field {
		case "timeout":
			if dep.Instance.Timeout > 0 {
				return dep.Instance.Timeout
			}
		case "extend_time":
			if dep.Instance.ExtendTime > 0 {
				return dep.Instance.ExtendTime
			}
		}
	}
	if cfg != nil && cfg.Instancer != nil {
		switch field {
		case "timeout":
			if cfg.Instancer.DefaultTimeout > 0 {
				return cfg.Instancer.DefaultTimeout
			}
		case "extend_time":
			if cfg.Instancer.DefaultExtendTime > 0 {
				return cfg.Instancer.DefaultExtendTime
			}
		}
	}
	if field == "timeout" {
		return 1800
	}
	return 900
}
