package generate

import (
	"bytes"
	"fmt"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/MicroClub-USTHB/mctf-cli/internal/challenge"
	"github.com/MicroClub-USTHB/mctf-cli/internal/config"
)

// ctfdManifest mirrors the shape of schema/ctfd-manifest.schema.json.
// Field order is the rendered order — yaml.v3 honors struct field order.
type ctfdManifest struct {
	Name           string     `yaml:"name"`
	Description    string     `yaml:"description"`
	Author         string     `yaml:"author"`
	Category       string     `yaml:"category"`
	Value          *int       `yaml:"value"`
	Type           string     `yaml:"type"`
	Extra          *ctfdExtra `yaml:"extra,omitempty"`
	Flags          []ctfdFlag `yaml:"flags"`
	Tags           []string   `yaml:"tags,omitempty"`
	Hints          []ctfdHint `yaml:"hints,omitempty"`
	ConnectionInfo *string    `yaml:"connection_info"`
	Files          []string   `yaml:"files"`
	State          string     `yaml:"state"`
}

type ctfdExtra struct {
	Initial int `yaml:"initial"`
	Decay   int `yaml:"decay"`
	Minimum int `yaml:"minimum"`
}

type ctfdFlag struct {
	Type          string `yaml:"type"`
	Content       string `yaml:"content"`
	CaseSensitive string `yaml:"case_sensitive"`
}

type ctfdHint struct {
	Content string `yaml:"content"`
	Cost    int    `yaml:"cost"`
}

// CTFdManifest renders the CTFd-format manifest for a challenge.
//
// The output is byte-deterministic across runs given identical inputs.
func CTFdManifest(cfg *config.Config, c *challenge.Challenge) ([]byte, error) {
	m := c.Manifest
	mf := ctfdManifest{
		Name:        m.Challenge.Name,
		Description: descriptionWithAuthor(m.Challenge.Description, m.Challenge.Author),
		Author:      m.Challenge.Author,
		Category:    m.Challenge.Category,
	}

	// Scoring: per-challenge override, else event default, else static-1pt fallback.
	scoring := resolveScoring(cfg, m.Challenge.Scoring)
	if scoring.Type == "static" {
		v := scoring.Points
		mf.Value = &v
		mf.Type = "standard"
	} else {
		mf.Type = "dynamic"
		mf.Extra = &ctfdExtra{
			Initial: scoring.Initial,
			Decay:   scoring.Decay,
			Minimum: scoring.Minimum,
		}
	}

	// Flags
	for _, f := range m.Challenge.Flags {
		cs := "case_insensitive"
		if f.CaseSensitive {
			cs = "case_sensitive"
		}
		mf.Flags = append(mf.Flags, ctfdFlag{
			Type:          "static",
			Content:       f.Flag,
			CaseSensitive: cs,
		})
	}

	// Tags: "wave N" auto-prefixed, then any explicit tags.
	mf.Tags = append(mf.Tags, fmt.Sprintf("wave %d", m.Challenge.Wave))
	mf.Tags = append(mf.Tags, m.Challenge.Tags...)

	// Hints (only emitted when non-empty)
	for _, h := range m.Challenge.Hints {
		mf.Hints = append(mf.Hints, ctfdHint{Content: h.Content, Cost: h.Cost})
	}

	// connection_info: derived from archetype + deploy
	mf.ConnectionInfo = connectionInfo(cfg, c)

	// files: paths relative to the challenge root
	mf.Files = listAssets(c)

	// state: hidden if force_hidden, otherwise visible
	if m.Challenge.ForceHidden {
		mf.State = "hidden"
	} else {
		mf.State = "visible"
	}

	var buf bytes.Buffer
	buf.WriteString("# CTFd Challenge File, generated by MCTF (do not edit this file directly)\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(mf); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return normalizeYAML(buf.Bytes()), nil
}

// descriptionWithAuthor appends an "**Author: <handle>**" line to the
// challenge description, matching MCTF 5.0's existing format.
func descriptionWithAuthor(desc, author string) string {
	desc = strings.TrimRight(desc, "\n")
	if author == "" {
		return desc
	}
	return desc + "\n\n**Author: " + author + "**"
}

// normalizeYAML enforces \n line endings and a single trailing newline.
func normalizeYAML(b []byte) []byte {
	s := strings.ReplaceAll(string(b), "\r\n", "\n")
	s = strings.TrimRight(s, "\n") + "\n"
	return []byte(s)
}
