package generate

import (
	"bytes"
	"sort"
	

	"github.com/MicroClub-USTHB/mctf-cli/internal/challenge"
	"github.com/MicroClub-USTHB/mctf-cli/internal/config"
)

func PrometheusConfig(cfg *config.Config, challs []*challenge.Challenge) ([]byte, error) {
	var buf bytes.Buffer

	buf.WriteString("#Auto generated by MCTF\n")
	buf.WriteString("scrape config :\n")

	sort.Slice(challs, func(i, j int) bool {
		return challs[i].Slug < challs[j].Slug
	})

	return nil, nil
}
