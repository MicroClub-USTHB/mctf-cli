// Package ingress generates routing config for the deploy mode's
// chosen ingress (Traefik in v0).
//
// Output is byte-deterministic so `mctf generate --check` covers it.
// Only service-archetype, deployable challenges produce ingress
// entries; instanced challenges are handled by the instancer at game
// time, not by the event-deploy ingress.
package ingress

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/MicroClub-USTHB/mctf-cli/internal/challenge"
	"github.com/MicroClub-USTHB/mctf-cli/internal/config"
)

// composeShape mirrors the docker-compose subset we need. Re-defined
// here to avoid a dependency on internal/validate.
type composeShape struct {
	Services map[string]composeService `json:"services"`
}

type composeService struct {
	ContainerName string `json:"container_name"`
	Build         any    `json:"build"`
	Ports         []any  `json:"ports"`
	Image         string `json:"image"`
}

// Entry describes one resolved ingress entry. Pure data — used by both
// the YAML emitter and tests.
type Entry struct {
	Challenge string // <category>/<slug>
	Name      string // traefik router/service id (mctf-<event>-<cat>-<slug>)
	HostRule  string // Host(`<sub>.<domain>`) or HostSNI(`<sub>.<domain>`)
	TCP       bool
	NoSSL     bool
	Subdomain string
	Domain    string
	Backend   string // host:port (or http://host:port for HTTP)
	EntryPt   string // websecure | web | tcp
}

// PlanEntries walks deployable, service-archetype challenges and emits
// the Traefik routing entries for them. Instanced challenges are
// skipped — they are routed by the instancer.
func PlanEntries(cfg *config.Config, challs []*challenge.Challenge) ([]Entry, error) {
	var out []Entry
	domain := cfg.Event.Domain
	for _, c := range challs {
		if c.Archetype != challenge.ArchetypeService {
			continue
		}
		if c.Manifest.Deploy == nil {
			continue
		}
		d := c.Manifest.Deploy
		if d.Subdomain == "" {
			return nil, fmt.Errorf("%s/%s: deploy.subdomain is required for ingress generation", c.CategoryDir, c.Slug)
		}

		project := projectName(cfg, c)
		// Traefik connects to the container's listening port (inside
		// the docker network), which is internal_port. The host port
		// is irrelevant for in-network routing.
		if d.InternalPort == nil || *d.InternalPort == 0 {
			return nil, fmt.Errorf("%s/%s: deploy.internal_port is required for ingress (the container's listening port)", c.CategoryDir, c.Slug)
		}
		port := *d.InternalPort

		container, err := targetContainer(project, filepath.Join(c.ChallengeDir, "docker-compose.yml"), port)
		if err != nil {
			return nil, fmt.Errorf("%s/%s: %w", c.CategoryDir, c.Slug, err)
		}

		entry := Entry{
			Challenge: c.CategoryDir + "/" + c.Slug,
			Name:      fmt.Sprintf("mctf-%s-%s-%s", cfg.Event.Slug, c.CategoryDir, c.Slug),
			Subdomain: d.Subdomain,
			Domain:    domain,
			TCP:       d.TCP,
			NoSSL:     d.NoSSL,
		}
		host := d.Subdomain + "." + domain
		if d.TCP {
			entry.HostRule = "HostSNI(`" + host + "`)"
			entry.Backend = fmt.Sprintf("%s:%d", container, port)
			entry.EntryPt = "tcp"
		} else {
			entry.HostRule = "Host(`" + host + "`)"
			scheme := "http"
			entry.Backend = fmt.Sprintf("%s://%s:%d", scheme, container, port)
			entry.EntryPt = "websecure"
			if d.NoSSL {
				entry.EntryPt = "web"
			}
		}
		out = append(out, entry)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// TraefikDynamic renders the Traefik file-provider dynamic config.
//
// Layout: top-level `http` and `tcp` sections, each with `routers` and
// `services`. Keys are sorted; field order is fixed; no timestamps.
func TraefikDynamic(entries []Entry) []byte {
	var http, tcp []Entry
	for _, e := range entries {
		if e.TCP {
			tcp = append(tcp, e)
		} else {
			http = append(http, e)
		}
	}
	sort.Slice(http, func(i, j int) bool { return http[i].Name < http[j].Name })
	sort.Slice(tcp, func(i, j int) bool { return tcp[i].Name < tcp[j].Name })

	var b bytes.Buffer
	b.WriteString("# Auto-generated by MCTF (do not edit this file directly)\n")
	if len(http) > 0 {
		b.WriteString("http:\n")
		b.WriteString("  routers:\n")
		for _, e := range http {
			fmt.Fprintf(&b, "    %s:\n", e.Name)
			fmt.Fprintf(&b, "      rule: %s\n", e.HostRule)
			fmt.Fprintf(&b, "      service: %s\n", e.Name)
			fmt.Fprintf(&b, "      entryPoints: [%s]\n", e.EntryPt)
			if !e.NoSSL {
				b.WriteString("      tls: {}\n")
			}
		}
		b.WriteString("  services:\n")
		for _, e := range http {
			fmt.Fprintf(&b, "    %s:\n", e.Name)
			fmt.Fprintf(&b, "      loadBalancer:\n")
			fmt.Fprintf(&b, "        servers:\n")
			fmt.Fprintf(&b, "          - url: %s\n", e.Backend)
		}
	}
	if len(tcp) > 0 {
		b.WriteString("tcp:\n")
		b.WriteString("  routers:\n")
		for _, e := range tcp {
			fmt.Fprintf(&b, "    %s:\n", e.Name)
			fmt.Fprintf(&b, "      rule: %s\n", e.HostRule)
			fmt.Fprintf(&b, "      service: %s\n", e.Name)
			fmt.Fprintf(&b, "      entryPoints: [%s]\n", e.EntryPt)
			if !e.NoSSL {
				b.WriteString("      tls:\n        passthrough: true\n")
			}
		}
		b.WriteString("  services:\n")
		for _, e := range tcp {
			fmt.Fprintf(&b, "    %s:\n", e.Name)
			fmt.Fprintf(&b, "      loadBalancer:\n")
			fmt.Fprintf(&b, "        servers:\n")
			fmt.Fprintf(&b, "          - address: %s\n", e.Backend)
		}
	}
	return b.Bytes()
}

// TraefikStatic renders the Traefik static config (entryPoints, file
// provider directory). Customize for production TLS resolvers; this
// emits a sane, opinionated baseline.
func TraefikStatic(cfg *config.Config) []byte {
	var b bytes.Buffer
	b.WriteString("# Auto-generated by MCTF (do not edit this file directly)\n")
	b.WriteString("log:\n  level: INFO\n")
	b.WriteString("api:\n  dashboard: true\n  insecure: false\n")
	b.WriteString("entryPoints:\n")
	b.WriteString("  web:\n    address: \":80\"\n")
	b.WriteString("  websecure:\n    address: \":443\"\n")
	b.WriteString("  tcp:\n    address: \":31337\"\n")
	b.WriteString("providers:\n")
	b.WriteString("  file:\n")
	b.WriteString("    directory: /etc/traefik/dynamic\n")
	b.WriteString("    watch: true\n")
	return b.Bytes()
}

func projectName(cfg *config.Config, c *challenge.Challenge) string {
	return fmt.Sprintf("mctf-%s-%s-%s", cfg.Event.Slug, c.CategoryDir, c.Slug)
}

// targetContainer resolves the target container name for Traefik routing.
// If the selected service sets an explicit container_name, that name is used directly
// without project prefix or -1 suffix. Otherwise, the standard Compose container
// name "<project>-<service>-1" is used.
func targetContainer(project, path string, internalPort int) (string, error) {
	svcName, containerName, err := selectService(path, internalPort)
	if err != nil {
		return "", err
	}
	if containerName != "" {
		return containerName, nil
	}
	return fmt.Sprintf("%s-%s-1", project, svcName), nil
}

// composeServiceName returns the selected service name from the compose
// file (or explicit container_name if set).
func composeServiceName(path string) (string, error) {
	svcName, containerName, err := selectService(path, 0)
	if err != nil {
		return "", err
	}
	if containerName != "" {
		return containerName, nil
	}
	return svcName, nil
}

// selectService picks the primary service from a compose file. When multiple
// services exist, it prefers services that declare ports matching internalPort,
// then services declaring ports, then services with a build block, and finally
// falls back to alphabetical order.
func selectService(path string, internalPort int) (string, string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", "", fmt.Errorf("read %s: %w", path, err)
	}
	jsonBytes, err := yaml.YAMLToJSON(data)
	if err != nil {
		return "", "", fmt.Errorf("parse %s: %w", path, err)
	}
	var c composeShape
	if err := yaml.Unmarshal(jsonBytes, &c); err != nil {
		return "", "", fmt.Errorf("decode %s: %w", path, err)
	}
	if len(c.Services) == 0 {
		return "", "", fmt.Errorf("%s declares no services", path)
	}

	type candidate struct {
		name  string
		score int
		svc   composeService
	}

	candidates := make([]candidate, 0, len(c.Services))
	for name, svc := range c.Services {
		score := 0
		if internalPort > 0 && serviceMatchesPort(svc, internalPort) {
			score += 1000
		}
		if len(svc.Ports) > 0 {
			score += 100
		}
		if svc.Build != nil {
			score += 10
		}
		candidates = append(candidates, candidate{name: name, score: score, svc: svc})
	}

	sort.Slice(candidates, func(i, j int) bool {
		if candidates[i].score != candidates[j].score {
			return candidates[i].score > candidates[j].score
		}
		return candidates[i].name < candidates[j].name
	})

	winner := candidates[0]
	cn := ""
	if winner.svc.ContainerName != "" {
		cn = strings.TrimPrefix(winner.svc.ContainerName, "/")
	}
	return winner.name, cn, nil
}

func serviceMatchesPort(svc composeService, targetPort int) bool {
	for _, p := range svc.Ports {
		switch v := p.(type) {
		case int:
			if v == targetPort {
				return true
			}
		case float64:
			if int(v) == targetPort {
				return true
			}
		case string:
			clean := strings.TrimSpace(v)
			clean = strings.Split(clean, "/")[0]
			parts := strings.Split(clean, ":")
			portStr := parts[len(parts)-1]
			if parsed, err := strconv.Atoi(portStr); err == nil && parsed == targetPort {
				return true
			}
		case map[string]any:
			if target, ok := v["target"]; ok {
				if tFloat, ok := target.(float64); ok && int(tFloat) == targetPort {
					return true
				}
				if tInt, ok := target.(int); ok && tInt == targetPort {
					return true
				}
			}
		}
	}
	return false
}
