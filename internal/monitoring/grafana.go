package monitoring

// datasourceUID is the fixed Prometheus datasource UID. The overview
// dashboard references it literally so a provisioned (non-imported)
// dashboard resolves its panels without import-time input substitution.
const datasourceUID = "mctf-prometheus"

// GrafanaDatasource renders the datasource provisioning file that points
// Grafana at the in-stack Prometheus. The URL uses the compose service name
// and the in-container port (always 9090), not the host-mapped port.
func GrafanaDatasource(_ Options) []byte {
	return []byte(`# Auto-generated by MCTF. Do not edit by hand.
apiVersion: 1
datasources:
  - name: Prometheus
    type: prometheus
    uid: ` + datasourceUID + `
    access: proxy
    url: http://prometheus:9090
    isDefault: true
    editable: false
`)
}

// GrafanaDashboardProvider renders the dashboard provider file that tells
// Grafana to load every dashboard JSON under /var/lib/grafana/dashboards.
func GrafanaDashboardProvider() []byte {
	return []byte(`# Auto-generated by MCTF. Do not edit by hand.
apiVersion: 1
providers:
  - name: MCTF
    orgId: 1
    folder: MCTF
    type: file
    disableDeletion: false
    updateIntervalSeconds: 30
    allowUiUpdates: true
    options:
      path: /var/lib/grafana/dashboards
      foldersFromFilesStructure: false
`)
}

// OverviewDashboard renders a minimal but real container-overview dashboard
// (per-container CPU and memory, sourced from cAdvisor). It is intentionally
// small and dependency-free so it provisions cleanly on a fresh Grafana.
//
// Queries filter on the cgroup `id` label (`/docker/<id>`) rather than the
// `name` label: native Linux cAdvisor populates `name`, but cAdvisor inside
// the Docker Desktop VM leaves it empty, so a `name!=""` filter would yield
// empty panels there. A nested label_replace derives a readable `container`
// label — the container name when present, else the short cgroup id — so the
// legend stays useful on both.
func OverviewDashboard() []byte {
	const dash = `{
  "annotations": {"list": []},
  "editable": true,
  "schemaVersion": 39,
  "title": "MCTF — Container Overview",
  "uid": "mctf-overview",
  "tags": ["mctf"],
  "time": {"from": "now-1h", "to": "now"},
  "refresh": "30s",
  "templating": {"list": []},
  "panels": [
    {
      "id": 1,
      "title": "CPU usage by container",
      "type": "timeseries",
      "datasource": {"type": "prometheus", "uid": "` + datasourceUID + `"},
      "gridPos": {"h": 9, "w": 24, "x": 0, "y": 0},
      "fieldConfig": {"defaults": {"unit": "percentunit"}, "overrides": []},
      "targets": [
        {
          "datasource": {"type": "prometheus", "uid": "` + datasourceUID + `"},
          "expr": "label_replace(label_replace(sum(rate(container_cpu_usage_seconds_total{id=~\"/docker/[^/]+\"}[5m])) by (name, id), \"container\", \"$1\", \"id\", \"/docker/(.{0,12}).*\"), \"container\", \"$1\", \"name\", \"(.+)\")",
          "legendFormat": "{{container}}",
          "refId": "A"
        }
      ]
    },
    {
      "id": 2,
      "title": "Memory usage by container",
      "type": "timeseries",
      "datasource": {"type": "prometheus", "uid": "` + datasourceUID + `"},
      "gridPos": {"h": 9, "w": 24, "x": 0, "y": 9},
      "fieldConfig": {"defaults": {"unit": "bytes"}, "overrides": []},
      "targets": [
        {
          "datasource": {"type": "prometheus", "uid": "` + datasourceUID + `"},
          "expr": "label_replace(label_replace(sum(container_memory_usage_bytes{id=~\"/docker/[^/]+\"}) by (name, id), \"container\", \"$1\", \"id\", \"/docker/(.{0,12}).*\"), \"container\", \"$1\", \"name\", \"(.+)\")",
          "legendFormat": "{{container}}",
          "refId": "A"
        }
      ]
    }
  ]
}
`
	return []byte(dash)
}
