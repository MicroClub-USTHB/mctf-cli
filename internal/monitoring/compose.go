package monitoring

import (
	"bytes"
	"fmt"
)

// Pinned image versions. Kept explicit so a `monitoring up` is reproducible
// and never silently pulls a new major on a fresh host.
const (
	prometheusImage = "prom/prometheus:v2.53.2"
	grafanaImage    = "grafana/grafana:11.2.0"
	cadvisorImage   = "gcr.io/cadvisor/cadvisor:v0.49.1"
)

// ComposeConfig renders the docker-compose.yml for the monitoring stack.
//
// Prometheus reads the rendered prometheus.yml; Grafana auto-provisions the
// Prometheus datasource and the overview dashboard; cAdvisor exposes
// per-container metrics by mounting the host's read-only cgroup/docker paths.
// extra_hosts wires host.docker.internal to the host gateway so Prometheus
// can scrape challenge services published on the host.
func ComposeConfig(opts Options) []byte {
	var b bytes.Buffer

	b.WriteString("# Auto-generated by MCTF — monitoring stack. Do not edit by hand.\n")
	b.WriteString("# Brought up and torn down by `mctf monitoring up` / `mctf monitoring down`.\n")
	b.WriteString("name: mctf-monitoring\n\n")
	b.WriteString("services:\n")

	// Prometheus
	fmt.Fprintf(&b, "  prometheus:\n")
	fmt.Fprintf(&b, "    image: %s\n", prometheusImage)
	fmt.Fprintf(&b, "    container_name: mctf-prometheus\n")
	fmt.Fprintf(&b, "    restart: unless-stopped\n")
	fmt.Fprintf(&b, "    command:\n")
	fmt.Fprintf(&b, "      - --config.file=/etc/prometheus/prometheus.yml\n")
	fmt.Fprintf(&b, "      - --storage.tsdb.path=/prometheus\n")
	fmt.Fprintf(&b, "      - --storage.tsdb.retention.time=%s\n", opts.Retention)
	fmt.Fprintf(&b, "    volumes:\n")
	fmt.Fprintf(&b, "      - ./prometheus.yml:/etc/prometheus/prometheus.yml:ro\n")
	fmt.Fprintf(&b, "      - prometheus-data:/prometheus\n")
	fmt.Fprintf(&b, "    ports:\n")
	fmt.Fprintf(&b, "      - %q\n", fmt.Sprintf("%d:9090", opts.PrometheusPort))
	fmt.Fprintf(&b, "    extra_hosts:\n")
	fmt.Fprintf(&b, "      - %q\n", fmt.Sprintf("%s:host-gateway", HostGateway))

	// cAdvisor
	fmt.Fprintf(&b, "  cadvisor:\n")
	fmt.Fprintf(&b, "    image: %s\n", cadvisorImage)
	fmt.Fprintf(&b, "    container_name: mctf-cadvisor\n")
	fmt.Fprintf(&b, "    restart: unless-stopped\n")
	fmt.Fprintf(&b, "    privileged: true\n")
	fmt.Fprintf(&b, "    volumes:\n")
	fmt.Fprintf(&b, "      - /:/rootfs:ro\n")
	fmt.Fprintf(&b, "      - /var/run:/var/run:ro\n")
	fmt.Fprintf(&b, "      - /sys:/sys:ro\n")
	fmt.Fprintf(&b, "      - /var/lib/docker/:/var/lib/docker:ro\n")
	fmt.Fprintf(&b, "      - /dev/disk/:/dev/disk:ro\n")
	fmt.Fprintf(&b, "    ports:\n")
	fmt.Fprintf(&b, "      - %q\n", fmt.Sprintf("%d:%d", opts.CadvisorPort, cadvisorInternalPort))

	// Grafana
	fmt.Fprintf(&b, "  grafana:\n")
	fmt.Fprintf(&b, "    image: %s\n", grafanaImage)
	fmt.Fprintf(&b, "    container_name: mctf-grafana\n")
	fmt.Fprintf(&b, "    restart: unless-stopped\n")
	fmt.Fprintf(&b, "    depends_on:\n")
	fmt.Fprintf(&b, "      - prometheus\n")
	fmt.Fprintf(&b, "    environment:\n")
	fmt.Fprintf(&b, "      - GF_SECURITY_ADMIN_PASSWORD=%s\n", opts.GrafanaPassword)
	fmt.Fprintf(&b, "      - GF_USERS_ALLOW_SIGN_UP=false\n")
	fmt.Fprintf(&b, "    volumes:\n")
	fmt.Fprintf(&b, "      - ./grafana/provisioning:/etc/grafana/provisioning:ro\n")
	fmt.Fprintf(&b, "      - ./grafana/dashboards:/var/lib/grafana/dashboards:ro\n")
	fmt.Fprintf(&b, "      - grafana-data:/var/lib/grafana\n")
	fmt.Fprintf(&b, "    ports:\n")
	fmt.Fprintf(&b, "      - %q\n", fmt.Sprintf("%d:3000", opts.GrafanaPort))

	b.WriteString("\nvolumes:\n")
	b.WriteString("  prometheus-data:\n")
	b.WriteString("  grafana-data:\n")

	return b.Bytes()
}
