package monitoring

import (
	"bytes"
	"fmt"
	"sort"

	"github.com/MicroClub-USTHB/mctf-cli/internal/challenge"
)

// HostGateway is the DNS name Prometheus uses to reach challenge services
// published on the host. The compose file maps it to host-gateway via
// extra_hosts, so a target of "<HostGateway>:<port>" resolves to the host
// from inside the prometheus container — unlike the "localhost:<port>"
// targets in the generate-side scrape config, which only work when
// Prometheus runs directly on the host.
const HostGateway = "host.docker.internal"

// prometheusInternalPort is the port Prometheus listens on inside its
// container. Scrape targets resolve from inside the container, so the
// self-scrape job uses this fixed port — never the host-mapped port.
const prometheusInternalPort = 9090

// PrometheusConfig renders the full Prometheus config for the monitoring
// stack: a global block, self- and cAdvisor-scrape jobs, and one job per
// instanced challenge pointed at the host gateway.
//
// All targets resolve from inside the Prometheus container, so the infra
// jobs use in-container ports (prometheus 9090, cadvisor 8080) and the
// challenge jobs use the host gateway — never the host-mapped ports.
//
// This is a superset of generate.PrometheusConfig (which emits only the
// challenge jobs, as a derived file for operators). The stack needs the
// extra infra jobs and host-reachable targets, so it renders its own copy
// rather than consuming the derived file.
func PrometheusConfig(challs []*challenge.Challenge) ([]byte, error) {
	var buf bytes.Buffer

	buf.WriteString("# Auto-generated by MCTF — monitoring stack config. Do not edit by hand.\n")
	buf.WriteString("global:\n")
	buf.WriteString("  scrape_interval: 15s\n")
	buf.WriteString("  evaluation_interval: 15s\n")
	buf.WriteString("scrape_configs:\n")

	writeJob(&buf, "prometheus", fmt.Sprintf("localhost:%d", prometheusInternalPort))
	writeJob(&buf, "cadvisor", fmt.Sprintf("cadvisor:%d", cadvisorInternalPort))

	sorted := append([]*challenge.Challenge(nil), challs...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Slug < sorted[j].Slug })

	for _, c := range sorted {
		if c.Archetype != challenge.ArchetypeInstanced {
			continue
		}
		if c.Manifest.Deploy == nil || c.Manifest.Deploy.InternalPort == nil {
			continue
		}
		writeJob(&buf, c.Slug, fmt.Sprintf("%s:%d", HostGateway, *c.Manifest.Deploy.InternalPort))
	}

	return buf.Bytes(), nil
}

func writeJob(buf *bytes.Buffer, job, target string) {
	fmt.Fprintf(buf, "  - job_name: %q\n", job)
	fmt.Fprintf(buf, "    static_configs:\n")
	fmt.Fprintf(buf, "      - targets:\n")
	fmt.Fprintf(buf, "          - %q\n", target)
}
